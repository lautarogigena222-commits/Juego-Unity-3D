using UnityEngine;

public class Enter : MonoBehaviour
{
    
    void Start()
    {
        
    }

    // Update is called once per frame
    void Update()
    {
        
    }

    private void OnTriggerEnter(Collider other)
    {
        if (other.CompareTag("Player"))
        {
            Instantiate(other.gameObject, transform.position, Quaternion.identity);
        }

    }
}
